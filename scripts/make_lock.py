"""Write requirements.lock.txt: the exact, tested versions of requirements.txt.

Offline: it reads the installed package metadata of the environment it runs
in (run it from the venv the test suite passed in), starts at the packages
named in requirements.txt and follows their dependencies. Packages a plugin
installs for itself later (Telegram, Discord, Slack...) or that a user added
to their own venv are not reachable from requirements.txt and so are never
locked. The installer installs from this file so every install gets the
versions that were tested.

Every pin carries the SHA-256 of each file PyPI publishes for that version
(read from PyPI's JSON API; nothing is downloaded), so installs run
`pip install --require-hashes -r requirements.lock.txt` and refuse any file
that is not exactly the one locked here: a changed or substituted package on
the index fails the install instead of running.

    .venv\\Scripts\\python.exe scripts\\make_lock.py
"""

from __future__ import annotations

import json
import re
import sys
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REQUIREMENTS = ROOT / "requirements.txt"
LOCK = ROOT / "requirements.lock.txt"

_NAME = re.compile(r"^\s*([A-Za-z0-9][A-Za-z0-9._-]*)")


def canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def top_level_names(text: str) -> list[str]:
    names = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line or line.startswith(("-", "git+", "http")):
            continue
        match = _NAME.match(line)
        if match:
            names.append(match.group(1))
    return names


def _requires(dist: metadata.Distribution, extras: set[str]) -> list[tuple[str, set[str]]]:
    out = []
    for req in dist.requires or []:
        spec, _, marker = req.partition(";")
        marker = marker.strip()
        extra_match = re.search(r"extra\s*==\s*['\"]([^'\"]+)['\"]", marker)
        if extra_match and extra_match.group(1) not in extras:
            continue
        if marker and not extra_match and not _marker_applies(marker):
            continue
        name_match = _NAME.match(spec)
        if not name_match:
            continue
        wanted = set()
        bracket = re.search(r"\[([^\]]+)\]", spec)
        if bracket:
            wanted = {e.strip() for e in bracket.group(1).split(",")}
        out.append((name_match.group(1), wanted))
    return out


def _marker_applies(marker: str) -> bool:
    try:
        from packaging.markers import Marker

        return Marker(marker).evaluate()
    except Exception:
        return True  # unknown: lock it rather than miss a dependency


def closure(names: list[str]) -> dict[str, str]:
    installed = {canonical(d.metadata["Name"]): d for d in metadata.distributions()}
    locked: dict[str, str] = {}
    queue = [(n, set()) for n in names]
    for spec in REQUIREMENTS.read_text(encoding="utf-8").splitlines():
        bracket = re.match(r"^\s*([A-Za-z0-9._-]+)\[([^\]]+)\]", spec)
        if bracket:
            queue.append((bracket.group(1), {e.strip() for e in bracket.group(2).split(",")}))
    seen: set[tuple[str, frozenset]] = set()
    missing = []
    while queue:
        name, extras = queue.pop()
        key = (canonical(name), frozenset(extras))
        if key in seen:
            continue
        seen.add(key)
        dist = installed.get(canonical(name))
        if dist is None:
            missing.append(name)
            continue
        locked[dist.metadata["Name"]] = dist.version
        queue.extend(_requires(dist, extras))
    if missing:
        top = {canonical(n) for n in names}
        hard = [m for m in missing if canonical(m) in top]
        if hard:
            raise SystemExit(f"Not installed in this environment: {', '.join(sorted(hard))}")
    return locked


PYPI = "https://pypi.org/pypi/{name}/{version}/json"
CONTINUATION = " " + chr(92)


def file_hashes(name: str, version: str) -> list[str]:
    """SHA-256 of every file PyPI publishes for name==version (sorted)."""
    with urllib.request.urlopen(PYPI.format(name=name, version=version), timeout=60) as resp:
        data = json.load(resp)
    hashes = sorted({f["digests"]["sha256"] for f in data.get("urls", []) if f.get("digests", {}).get("sha256")})
    if not hashes:
        raise SystemExit(f"PyPI publishes no files with a SHA-256 for {name}=={version}")
    return hashes


def main() -> int:
    names = top_level_names(REQUIREMENTS.read_text(encoding="utf-8"))
    locked = closure(names)
    ordered = sorted(locked.items(), key=lambda kv: kv[0].lower())
    with ThreadPoolExecutor(max_workers=8) as pool:
        hashes = list(pool.map(lambda kv: file_hashes(*kv), ordered))
    lines = [
        "# Exact versions the test suite passed with. Generated by scripts/make_lock.py",
        "# from requirements.txt - do not edit by hand; edit requirements.txt and regenerate.",
        "# Install with: pip install --require-hashes -r requirements.lock.txt",
        f"# Python {sys.version_info.major}.{sys.version_info.minor}",
    ]
    for (name, version), file_sums in zip(ordered, hashes):
        lines.append(f"{name}=={version}" + CONTINUATION)
        for i, digest in enumerate(file_sums):
            lines.append(f"    --hash=sha256:{digest}" + (CONTINUATION if i < len(file_sums) - 1 else ""))
    LOCK.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{LOCK.name}: {len(locked)} packages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
